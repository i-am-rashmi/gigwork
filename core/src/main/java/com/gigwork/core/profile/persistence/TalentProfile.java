package com.gigwork.core.profile.persistence;

import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;

import org.hibernate.annotations.Immutable;

import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Embeddable;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;

/**
 * The read side of a profile. Read-only: every write is a native statement under the profile row's lock (see
 * {@link ProfileStore}). The status is generated by the database. Collections are lazy and read inside the reader's
 * transaction.
 */
@Entity
@Immutable
@Table(schema = "profile", name = "talent_profile")
class TalentProfile {

	@Id
	@Column(name = "account_id")
	private UUID accountId;
	@Column(name = "profile_type")
	private String profileType;
	@Column(name = "member_count")
	private Integer memberCount;
	private String headline;
	private String bio;
	private Double lat;
	private Double lng;
	@Column(name = "city_id")
	private UUID cityId;
	@Column(name = "zone_id")
	private UUID zoneId;
	@Column(name = "location_label")
	private String locationLabel;
	@Column(name = "locality_id")
	private UUID localityId;
	@Column(name = "service_radius_km")
	private Integer serviceRadiusKm;
	@Column(name = "willing_to_travel")
	private Boolean willingToTravel;
	private boolean hidden;
	private String status;
	@Column(name = "updated_at")
	private Instant updatedAt;

	@Immutable
	@ElementCollection(fetch = FetchType.LAZY)
	@CollectionTable(schema = "profile", name = "talent_category", joinColumns = @JoinColumn(name = "account_id"))
	@Column(name = "category_id")
	private Set<UUID> categoryIds = new HashSet<>();

	@Immutable
	@ElementCollection(fetch = FetchType.LAZY)
	@CollectionTable(schema = "profile", name = "talent_specialisation", joinColumns = @JoinColumn(name = "account_id"))
	private Set<SpecialisationRow> specialisations = new HashSet<>();

	@Immutable
	@ElementCollection(fetch = FetchType.LAZY)
	@CollectionTable(schema = "profile", name = "talent_language", joinColumns = @JoinColumn(name = "account_id"))
	@Column(name = "language_code")
	private Set<String> languageCodes = new HashSet<>();

	@Immutable
	@ElementCollection(fetch = FetchType.LAZY)
	@CollectionTable(schema = "profile", name = "portfolio_link", joinColumns = @JoinColumn(name = "account_id"))
	@OrderBy("displayOrder ASC")
	private List<LinkRow> links = new ArrayList<>();

	protected TalentProfile() {
	}

	@Embeddable
	static class SpecialisationRow {

		@Column(name = "category_id")
		private UUID categoryId;
		@Column(name = "specialisation_id")
		private UUID specialisationId;

		protected SpecialisationRow() {
		}

		@Override
		public boolean equals(Object o) {
			return o instanceof SpecialisationRow other && specialisationId.equals(other.specialisationId)
					&& categoryId.equals(other.categoryId);
		}

		@Override
		public int hashCode() {
			return specialisationId.hashCode();
		}

	}

	@Embeddable
	static class LinkRow {

		private String url;
		private String type;
		@Column(name = "display_order")
		private int displayOrder;

		protected LinkRow() {
		}

	}

	StoredProfile toStored() {
		List<StoredProfile.Specialisation> specs = specialisations.stream()
				.map(s -> new StoredProfile.Specialisation(s.categoryId, s.specialisationId))
				.sorted(java.util.Comparator.comparing(StoredProfile.Specialisation::specialisationId)).toList();
		List<StoredProfile.Link> storedLinks = links.stream().map(l -> new StoredProfile.Link(l.url, l.type)).toList();
		return new StoredProfile(accountId, profileType, memberCount, headline, bio, lat != null, cityId, zoneId,
				locationLabel, localityId, serviceRadiusKm, willingToTravel, hidden, status,
				categoryIds.stream().sorted().toList(), specs, languageCodes.stream().sorted().toList(), storedLinks,
				updatedAt);
	}

}
